#!/usr/bin/env node
"use strict";
const fs = require("fs");
const path = require("path");
const { evaluateQuality } = require("./lib/build-contract");
const { resolveInside } = require("./lib/path-safety");
const root = path.resolve(process.argv[2] || process.cwd());
const result = evaluateQuality(root);
const out = resolveInside(root, "docs/agent-system/bootstrap-quality-report.md", "quality report");
const json = resolveInside(root, "docs/agent-system/bootstrap-quality-report.json", "quality evidence");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(json, `${JSON.stringify(result, null, 2)}\n`);
fs.writeFileSync(out, `# Bootstrap Quality Report

Generated by: \`reusable-agent-system-toolkit/scripts/generate-quality-report.js\`

- Full bootstrap quality: ${result.score}/10
- Статус проверяемого контракта: ${result.status}
- Project fingerprint: \`${result.projectFingerprint}\`
- Artifact fingerprint: \`${result.artifactFingerprint}\`

Это покрытие исполняемого контракта артефактов, а не оценка истинности исследования или инженерного мастерства. Количество рисков, строк и flows не повышает оценку. Отсутствие подтверждённых дефектов допустимо; выводы всё равно требуют ручного review.

| Категория | Score | Проверка / исправление |
| --- | --- | --- |
${result.checks.map((item) => `| ${item.category} | ${item.score}/10 | ${item.failures.length ? item.failures.join("; ").replaceAll("|", "\\|") : "проверяемый контракт выполнен"} |`).join("\n")}

Full bootstrap считается 10/10 только когда каждая категория равна 10/10. Финальный validator независимо пересчитывает контракт и сверяет fingerprint; редактирование этого отчёта не меняет результат.
`);
console.log(`Quality contract report generated: ${result.score}/10 (${result.status})`);
